# специфические казахские буквы (которых нет в русском алфавите)
KAZAKH_LETTERS = set("әғқңөұүһі")


def detect_lang(text):
    """Возвращает 'kz', если в тексте есть казахские буквы, иначе 'ru'."""
    if not text:
        return "ru"
    low = text.lower()
    if any(ch in KAZAKH_LETTERS for ch in low):
        return "kz"
    return "ru"



def t(key, lang="ru", **kwargs):
    """Возвращает текст по ключу на нужном языке, с подстановкой параметров."""
    entry = TEXTS.get(key, {})
    text = entry.get(lang) or entry.get("ru") or key
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, IndexError):
            pass
    return text



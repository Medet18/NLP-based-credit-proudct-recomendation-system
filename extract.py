# --- Распознавание запроса-справки ("что ты умеешь") --------------------------
HELP_PATTERNS = [
    r"что ты уме", r"что вы уме", r"что умеешь", r"как польз", r"как работа",
    r"\bпомощь\b", r"\bпомоги\b", r"что можешь", r"кто ты", r"\bпомог\b",
    r"не понимаю", r"көмек", r"не істей", r"қалай қолдан", r"сен не",
]


def is_help_query(text):
    """True, если запрос — вопрос о возможностях системы, а не подбор продукта."""
    t = text.lower()
    return any(re.search(p, t) for p in HELP_PATTERNS)


